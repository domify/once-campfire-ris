import sys,re
s=open(sys.argv[1]).read()
i=s.find('  <div id="message_bench-020"'); j=s.find('  <div id="message_bench-021"')
t=s[i:j]
assert t.endswith('\n\n'); t='\n\n'+t[:-2]
rep=[
 ('data-message-updated-at="1790846400000"','data-message-updated-at="\0UPD\0"'),
 ('1790846400000','\0MS\0'),
 ('2026-10-01T09:20:00Z','\0ISO\0'),
 ('bench-020','\0CID\0'),
 ('data-message-id="21"','data-message-id="\0MID\0"'),
 ('/rooms/1/@21','/rooms/\0RID\0/@\0MID\0'),
 ('/rooms/1/messages/21/edit','/rooms/\0RID\0/messages/\0MID\0/edit'),
 ('/messages/21/','/messages/\0MID\0/'),
 ('data-user-id="1"','data-user-id="\0UID\0"'),
 ('href="/users/1"','href="/users/\0UID\0"'),
]
for a,b in rep:
  assert a in t,a; t=t.replace(a,b)
t=re.sub(r'src="/users/[^"]*/avatar\?v=\d+"','src="\0AVATAR\0"',t)
t=t.replace('title="David"','title="\0NAME\0"').replace('>David<','>\0NAME\0<')
t=t.replace('>All Talk<','>\0ROOM\0<')
b=re.search(r'(<div class="lexxy-content">\n  )(.*?)(\n</div>)',t,re.S)
t=t[:b.start(2)]+'\0BODY\0'+t[b.end(2):]
assert 'David' not in t and '1790846' not in t and 'bench-0' not in t
parts=t.split('\0')
out=[open(sys.argv[3]).read(), "# Generated by bench/gen_markup.py from the Rust port's messages page: one message's markup.", "def render_markup(buf, m) : Nil"]
for k,p in enumerate(parts):
  if k%2==0:
    if p: out.append('  buf.append(%s)'%('"'+p.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n').replace('#{','\\#{')+'"'))
  else:
    out.append({'UPD':'  buf.append_int(m.updated_ms)','MS':'  buf.append_int(m.created_ms)','ISO':'  emit_iso(buf, m.created_s)','CID':'  buf.append_html_escaped(m.client_id)','MID':'  buf.append_int(m.id)','RID':'  buf.append_int(m.room_id)','UID':'  buf.append_int(m.user_id)','AVATAR':'  buf.append_html_escaped(m.avatar)','NAME':'  buf.append_html_escaped(m.name)','ROOM':'  buf.append_html_escaped(m.room_name)','BODY':'  buf.append(m.body)'}[p])
out.append("end")
out.append("\npub def render_message(buf : HeapBuf, m : MsgView) : Nil\n  render_markup(buf, m)\nend\n\npub def render_message(buf : TapeWriter, m : MsgView) : Nil\n  render_markup(buf, m)\nend")
open(sys.argv[2],'w').write("\n".join(out)+"\n")
print(len(parts)//2,"holes")
if len(sys.argv) > 4:
  import json
  json.dump(parts, open(sys.argv[4], 'w'))
